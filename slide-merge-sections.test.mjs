test('protected runtime media is temporary, validated and cancellable', async () => {
  const block = {type:'gallery',locked:true,items:[{src:'vault:private-original',caption:'Original'}]}, before = structuredClone(block);
  const signed = [];
  const source = {block,sign:async(key,options)=>{signed.push([key,options.strict]);return 'https://example.test/vault/file/original?sig=private';}};
  const runtime = await sectionRuntimeData(source);
  assert.deepEqual(signed,[['private-original',true]]);
  assert.equal(runtime.block.locked,false);
  assert.equal(runtime.media[runtime.block.items[0].src],'https://example.test/vault/file/original?sig=private');
  assert.deepEqual(block,before);
  assert.throws(()=>sectionComponentPlan(block,plain,'unsafe'),/Protected/);
  await assert.rejects(sectionRuntimeData({...source,sign:async()=> 'javascript:alert(1)'}),/not valid/);
  const controller = new AbortController();
  await assert.rejects(sectionRuntimeData({...source,sign:async()=>{controller.abort();return 'https://example.test/vault/file/original';}},controller.signal),{name:'AbortError'});
});
