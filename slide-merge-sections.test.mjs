test("section inserts opt into locked references without widening media or default AI sources", async () => {
  const source = {work:[{id:'case',study:{blocks:[{type:'text',body:'Public'},{type:'gallery',locked:true,vaultBlock:'opaque-key'},{type:'text',off:true,locked:true}]}}]};
  const values = new Map([['rk:content:draft',JSON.stringify(source)]]);
  const environment = {localStorage:{getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value)},dispatchEvent(){}};
  const prepared = await studioSectionSources(undefined,'case',environment);
  const sectionId = prepared.work[0].study.blocks[1].sectionId;
  assert.ok(sectionId);
  assert.equal(source.work[0].study.blocks[1].sectionId,undefined);
  assert.equal(availableStudies(prepared)[0].blocks.length,1);
  assert.equal(availableStudies(prepared,false,true)[0].blocks.length,2);
  const plan = sectionComponentPlan(prepared.work[0].study.blocks[1],plain,'insert',{caseStudyId:'case'});
  assert.equal(plan.elements[0].customData.sectionReference.sectionId,sectionId);
  assert.doesNotMatch(JSON.stringify(plan),/opaque-key/);
  prepared.work[0].study.blocks.reverse();
  values.set('rk:content:draft',JSON.stringify(prepared));
  const reopened = await studioSectionSources(undefined,'case',environment);
  assert.equal(reopened.work[0].study.blocks.find(block=>block.vaultBlock).sectionId,sectionId);
  const previous = values.get('rk:content:draft');
  environment.localStorage.setItem = () => {throw new Error('Storage full');};
  const changed = JSON.parse(previous);delete changed.work[0].study.blocks[1].sectionId;
  values.set('rk:content:draft',JSON.stringify(changed));
  await assert.rejects(studioSectionSources(undefined,'case',environment),/Storage full/);
  assert.equal(values.get('rk:content:draft'),JSON.stringify(changed));
});